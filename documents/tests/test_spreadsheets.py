class FormatCellValueTests(SimpleTestCase):
    def test_format_table(self):
        cases = [
            (42, "General", "42"),
            (1234.5, "General", "1234.5"),
            (1234.5, "#,##0.00", "1,234.50"),
            (-1234.5, "#,##0.00", "-1,234.50"),
            (0.15, "0%", "15%"),
            (0.1234, "0.00%", "12.34%"),
            (99.5, '"$"#,##0.00', "$99.50"),
            (1000, '#,##0.00" kr"', "1,000.00 kr"),
            (42, "@", "42"),
            (1234.5, "0.00E+00", "1234.5"),  # scientific: general fallback
            (True, "General", "TRUE"),
            ("abc\x00def", "General", "abcdef"),
            (datetime.datetime(2026, 1, 5), "yyyy-mm-dd", "2026-01-05"),
            (datetime.datetime(2026, 1, 5, 14, 30), "yyyy-mm-dd hh:mm", "2026-01-05 14:30"),
            (datetime.time(9, 5), "hh:mm", "09:05"),
            (None, "General", ""),
        ]
        for value, fmt, expected in cases:
            with self.subTest(value=value, fmt=fmt):
                self.assertEqual(format_cell_value(value, fmt), expected)

    def test_date_format_on_raw_number_falls_back(self):
        # openpyxl normally converts these to datetime; a raw number with a
        # date picture must not be mangled into digits-of-a-date.
        self.assertEqual(format_cell_value(45000, "yyyy-mm-dd"), "45000")


class LoadWorkbookModelTests(SimpleTestCase):
    def test_reads_values_structure_and_formats(self):
        from openpyxl import Workbook
        from openpyxl.formatting.rule import CellIsRule
        from openpyxl.styles import PatternFill

        wb = Workbook()
        ws = wb.active
        ws.title = "Main"
        ws.append(["Name", "Amount", "Status", "Hidden"])
        ws.append(["Alpha", 1234.5, "ACTIVE", "x"])
        ws["B2"].number_format = "#,##0.00"
        ws.append(["Beta", 0.15, "TERMINATED", "y"])
        ws["B3"].number_format = "0%"
        ws["A4"] = "Merged label"
        ws.merge_cells("A4:C4")
        ws["B5"] = "=B2*2"  # no cached value under data_only
        ws["A6"] = "hidden row value"
        ws.column_dimensions["A"].width = 10.57
        ws.column_dimensions["B"].width = 34.71
        ws.column_dimensions["D"].hidden = True
        ws.row_dimensions[3].height = 30
        ws.row_dimensions[6].hidden = True
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = "A1:C3"
        fill = PatternFill(start_color="FFC000", end_color="FFC000", fill_type="solid")
        ws.conditional_formatting.add(
            "C2:C10", CellIsRule(operator="equal", formula=['"TERMINATED"'], fill=fill)
        )
        hidden_sheet = wb.create_sheet("Secret")
        hidden_sheet["A1"] = "hidden"
        hidden_sheet.sheet_state = "hidden"

        with tempfile.TemporaryDirectory() as tmpdir:
            model = load_workbook_model(_save(wb, tmpdir))

        self.assertEqual(len(model.sheets), 1)
        self.assertEqual(model.hidden_sheets, ["Secret"])
        sheet = model.sheets[0]
        self.assertEqual(sheet.name, "Main")

        rows = dict(sheet.rows)
        # Formatted values, original coordinates.
        self.assertIn((2, "1,234.50"), rows[2])
        self.assertIn((2, "15%"), rows[3])
        # Hidden column D and hidden row 6 dropped; formula with no cached
        # value dropped.
        self.assertNotIn(4, [c for cells in rows.values() for c, _ in cells])
        self.assertNotIn(6, rows)
        self.assertNotIn(5, rows)
        # Structure from the XML supplement.
        self.assertEqual(sheet.col_widths[1], 10.57)
        self.assertEqual(sheet.col_widths[2], 34.71)
        self.assertEqual(sheet.hidden_cols, {4})
        self.assertEqual(sheet.hidden_rows, {6})
        self.assertEqual(sheet.row_heights[3], 30.0)
        self.assertIn((4, 1, 4, 3), sheet.merged)
        self.assertEqual(sheet.freeze_rows, 1)
        self.assertEqual(sheet.freeze_cols, 0)
        self.assertEqual(sheet.auto_filter, (1, 1, 3, 3))
        # cellIs CF evaluated during streaming.
        self.assertEqual(sheet.cf_fills.get((3, 3)), "#FFC000")
        self.assertNotIn((2, 3), sheet.cf_fills)

