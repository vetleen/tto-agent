def _sheet(rows, **kwargs) -> SheetModel:
    """Synthetic SheetModel: rows as {excel_row: {col: text}}."""
    sheet = SheetModel(name=kwargs.pop("name", "S"), index=kwargs.pop("index", 0))
    for key, value in kwargs.items():
        setattr(sheet, key, value)
    for r in sorted(rows):
        cells = sorted(rows[r].items())
        sheet.rows.append((r, [(c, t) for c, t in cells]))
        sheet.max_data_row = max(sheet.max_data_row, r)
        sheet.max_data_col = max([sheet.max_data_col] + [c for c, _ in cells])
        sheet.cell_count += len(cells)
    return sheet


class DetectHeadersTests(SimpleTestCase):
    def test_table_signal_wins(self):
        from documents.services.spreadsheets.model import TableInfo

        sheet = _sheet(
            {1: {1: "colA", 2: "colB"}, 2: {1: "1", 2: "2"}},
            tables=[TableInfo(name="T", bounds=(1, 1, 2, 2), header_row_count=1,
                              column_names=["Number", "Name"])],
            auto_filter=(1, 1, 2, 2),
        )
        info = detect_headers(sheet)
        self.assertEqual((info.signal, info.confidence), ("table", "definitive"))
        self.assertEqual(info.header_row, 1)
