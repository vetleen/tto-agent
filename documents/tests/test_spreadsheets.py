        self.assertEqual(len(body), 4)  # 7 data rows / 2 per chunk
        for chunk in body:
            row_lines = [ln for ln in chunk["text"].splitlines() if ln.startswith("Row ")]
            self.assertLessEqual(len(row_lines), 2)
            for line in row_lines:
                self.assertIn("value-", line)  # rows never split mid-line

