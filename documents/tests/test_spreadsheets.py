        self.assertTrue(manifest_mod.is_spreadsheet_manifest(manifest))
        self.assertEqual(manifest["renderer_rev"], mesh_mod.RENDERER_REV)
        entry = manifest["sheets"][0]
        self.assertEqual(entry["header"]["row"], 1)
        self.assertEqual(entry["header"]["signal"], "autofilter")
